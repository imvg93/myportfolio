-- Minimal, server-written transcript storage. No visitor-facing read policy is defined.
create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null,
  role text not null check (role in ('user', 'assistant')),
  content text not null check (char_length(content) between 1 and 20000),
  created_at timestamptz not null default now()
);

create index if not exists chat_messages_conversation_created_idx
  on public.chat_messages (conversation_id, created_at);
create index if not exists chat_messages_created_at_idx
  on public.chat_messages (created_at);

alter table public.chat_messages enable row level security;
revoke all on table public.chat_messages from public, anon, authenticated;
grant insert on table public.chat_messages to service_role;
revoke all on sequence public.chat_messages_id_seq from public, anon, authenticated;
grant usage, select on sequence public.chat_messages_id_seq to service_role;

-- Delete transcripts older than 180 days every day. Supabase projects support pg_cron;
-- this job runs as the database role that schedules it and does not expose a delete API.
create extension if not exists pg_cron;
do $$
begin
  if exists (select 1 from cron.job where jobname = 'delete-expired-chat-messages') then
    perform cron.unschedule(jobid)
    from cron.job
    where jobname = 'delete-expired-chat-messages';
  end if;
  perform cron.schedule(
    'delete-expired-chat-messages',
    '17 3 * * *',
    $job$delete from public.chat_messages where created_at < now() - interval '180 days'$job$
  );
end
$$;
